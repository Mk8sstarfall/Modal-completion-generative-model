"""
BraTS Dataset - Load from Preprocessed Data

Load samples from 2D slice data generated by the preprocessing script
"""

import json
from pathlib import Path
from typing import Dict, List, Optional
import numpy as np
import torch

from .base_dataset import BaseModalDataset


class BraTSDataset(BaseModalDataset):
    """
    BraTS (Brain Tumor Segmentation) Dataset - Preprocessed Version
    
    Load samples from preprocessed 2D slice data.
    Each sample is a 64x64 2D slice with 4 channels (one per modality).
    """
    
    MODALITIES = ['flair', 't1', 't1ce', 't2']
    
    def __init__(self,
                 data_root: str,
                 split: str = 'train',
                 **kwargs):
        """
        Initialize BraTS dataset
        
        Args:
            data_root: Root directory of preprocessed data
            split: One of 'train', 'val', 'test'
            **kwargs: Additional arguments for BaseModalDataset
        """
        super().__init__(
            data_root=data_root,
            num_modalities=4,
            channels_per_modality=1,
            **kwargs
        )
        
        self.split = split
        self.split_dir = Path(data_root) / split
        self.images_dir = self.split_dir / 'images'
        
        # Load metadata
        self.metadata = self._load_metadata()
        self.samples = self.metadata['samples']
        
        # Validate data
        self._validate_data()
        
        print(f"Loaded BraTS {split} set: {self.metadata['num_subjects']} subjects, "
              f"{len(self.samples)} samples")
    
    def _load_metadata(self) -> Dict:
        """Load metadata JSON file"""
        metadata_path = self.split_dir / 'metadata.json'
        
        if not metadata_path.exists():
            raise FileNotFoundError(
                f"Metadata file not found: {metadata_path}\n"
                f"Please run the preprocessing script preprocess_brats.py first"
            )
        
        with open(metadata_path, 'r') as f:
            metadata = json.load(f)
        
        return metadata
    
    def _validate_data(self):
        """Validate data integrity"""
        if not self.images_dir.exists():
            raise FileNotFoundError(
                f"Images directory not found: {self.images_dir}\n"
                f"Please run the preprocessing script preprocess_brats.py first"
            )
        
        # Check if all modality files exist for the first sample
        if len(self.samples) > 0:
            first_sample = self.samples[0]
            sample_name = first_sample['sample_name']
            
            for modality in self.MODALITIES:
                file_path = self.images_dir / f"{sample_name}_{modality}.npy"
                if not file_path.exists():
                    raise FileNotFoundError(
                        f"Missing file: {file_path}\n"
                        f"Data may be incomplete, please re-run the preprocessing script"
                    )
    
    def __len__(self) -> int:
        """Return total number of samples"""
        return len(self.samples)
    
    def _load_sample(self, idx: int) -> Dict[str, torch.Tensor]:
        """
        Load a single 2D slice sample
        
        Args:
            idx: Sample index
            
        Returns:
            Dictionary containing the sample data
        """
        sample_info = self.samples[idx]
        sample_name = sample_info['sample_name']
        
        # Load all modalities
        modality_data = []
        for modality in self.MODALITIES:
            file_path = self.images_dir / f"{sample_name}_{modality}.npy"
            data = np.load(file_path)  # Shape: (64, 64)
            modality_data.append(data)
        
        # Stack to (4, 64, 64)
        data_array = np.stack(modality_data, axis=0)
        
        # Convert to torch tensor
        data_tensor = torch.from_numpy(data_array).float()
        
        return {
            'data': data_tensor,
            'subject_idx': sample_info['subject_idx'],
            'subject_name': sample_info['subject_name'],
            'slice_idx': sample_info['slice_idx'],
            'z_position': sample_info['z_position'],
            'sample_name': sample_name,
            'idx': idx,
        }
    
    def get_modality_info(self) -> Dict[str, any]:
        """Get information about BraTS modalities"""
        return {
            'names': self.MODALITIES,
            'channels': [1] * 4,
            'type': 'mri',
            'dataset': 'BraTS2017',
            'description': {
                'flair': 'FLAIR (Fluid Attenuated Inversion Recovery)',
                't1': 'T1-weighted',
                't1ce': 'T1-weighted with contrast enhancement',
                't2': 'T2-weighted'
            }
        }
    
    def get_subject_info(self, idx: int) -> Dict[str, any]:
        """
        Get information about the subject for a given sample index
        
        Args:
            idx: Sample index
            
        Returns:
            Dictionary with subject information
        """
        sample_info = self.samples[idx]
        
        return {
            'subject_idx': sample_info['subject_idx'],
            'subject_name': sample_info['subject_name'],
            'slice_idx': sample_info['slice_idx'],
            'z_position': sample_info['z_position'],
            'sample_name': sample_info['sample_name'],
            'total_slices_per_subject': self.metadata['num_slices_per_subject']
        }
    
    def get_dataset_statistics(self) -> Dict[str, any]:
        """Get dataset statistics"""
        return {
            'split': self.split,
            'num_subjects': self.metadata['num_subjects'],
            'num_samples': len(self.samples),
            'num_slices_per_subject': self.metadata['num_slices_per_subject'],
            'crop_size': self.metadata['crop_size'],
            'target_size': self.metadata['target_size'],
            'modalities': self.MODALITIES
        }


def test_preprocessed_dataset():
    """Test the preprocessed dataset"""
    import matplotlib.pyplot as plt
    
    # Initialize dataset
    dataset = BraTSDataset(
        data_root='BRATS2017_processed',  # Update to preprocessed data path
        split='train',
        normalize=True,
        normalization_range=(-1.0, 1.0)
    )
    
    # Print dataset information
    print(f"Dataset size: {len(dataset)}")
    stats = dataset.get_dataset_statistics()
    print(f"Number of subjects: {stats['num_subjects']}")
    print(f"Slices per subject: {stats['num_slices_per_subject']}")
    print(f"Crop size: {stats['crop_size']}")
    
    # Load sample
    sample = dataset[0]
    print(f"\nSample keys: {sample.keys()}")
    print(f"Data shape: {sample['data'].shape}")
    print(f"Data range: [{sample['data'].min():.3f}, {sample['data'].max():.3f}]")
    print(f"Subject name: {sample['subject_name']}")
    print(f"Slice index: {sample['slice_idx']}")
    print(f"Z position: {sample['z_position']}")
    
    # Visualize
    vis_data = dataset.visualize_sample(0)
    
    fig, axes = plt.subplots(1, 4, figsize=(16, 4))
    for i, (name, data) in enumerate(vis_data.items()):
        axes[i].imshow(data[0], cmap='gray')
        axes[i].set_title(f'{name}')
        axes[i].axis('off')
    
    plt.tight_layout()
    plt.savefig('brats_preprocessed_sample.png', dpi=150, bbox_inches='tight')
    print("\nVisualization saved!")
    
    # Test loading speed
    import time
    start = time.time()
    for i in range(min(100, len(dataset))):
        _ = dataset[i]
    elapsed = time.time() - start
    print(f"\nTime to load 100 samples: {elapsed:.3f} seconds")
    print(f"Average per sample: {elapsed/100*1000:.2f} milliseconds")


if __name__ == '__main__':
    test_preprocessed_dataset()